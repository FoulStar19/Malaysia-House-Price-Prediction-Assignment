"""Loads the trained model + artifacts once at process start, and turns a
prediction request into a model call. This is the same logic that used to
live inline in the Streamlit app - it's just moved here so it can be reused
by the API layer without Streamlit involved at all.
"""
import pickle
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

APP_DIR = Path(__file__).resolve().parent

REQUIRED_FILES = [
    "best_model.pkl", "scaler.pkl", "feature_columns.pkl",
    "app_sample_listings.csv",
]


class Artifacts:
    def __init__(self, model, scaler, feature_columns, results_df, extra, sample_df, city_options):
        self.model = model
        self.scaler = scaler
        self.feature_columns = feature_columns
        self.results_df = results_df
        self.extra = extra
        self.sample_df = sample_df
        self.city_options = city_options


def extract_dummy_options(feature_columns: list, prefix: str) -> list:
    """Recover the category values pandas.get_dummies folded into
    `<prefix><value>` columns during training, so the API can offer exactly
    the categories the model was actually fit on (City, in particular, isn't
    hardcoded anywhere the way State/Tenure/etc. are in constants.py -
    ds_assignment.py buckets it into a variable top-N + "Other" at train
    time, so feature_columns.pkl is the only source of truth for it).
    """
    return sorted(col[len(prefix):] for col in feature_columns if col.startswith(prefix))


@lru_cache(maxsize=1)
def load_artifacts() -> Artifacts:
    missing = [f for f in REQUIRED_FILES if not (APP_DIR / f).exists()]
    if missing:
        raise FileNotFoundError(
            "Missing required file(s): " + ", ".join(missing) +
            f". Looked in {APP_DIR}. These are generated by ds_assignment.py "
            "and must sit alongside main.py in the backend folder."
        )

    with open(APP_DIR / "best_model.pkl", "rb") as f:
        model = pickle.load(f)
    with open(APP_DIR / "scaler.pkl", "rb") as f:
        scaler = pickle.load(f)
    with open(APP_DIR / "feature_columns.pkl", "rb") as f:
        feature_columns = pickle.load(f)

    results_df = None
    if (APP_DIR / "all_results.pkl").exists():
        with open(APP_DIR / "all_results.pkl", "rb") as f:
            results_df = pickle.load(f)

    extra = None
    if (APP_DIR / "extra_artifacts.pkl").exists():
        with open(APP_DIR / "extra_artifacts.pkl", "rb") as f:
            extra = pickle.load(f)

    sample_df = pd.read_csv(APP_DIR / "app_sample_listings.csv")
    city_options = extract_dummy_options(feature_columns, "City_")

    return Artifacts(model, scaler, feature_columns, results_df, extra, sample_df, city_options)


def build_feature_row(payload: dict, feature_columns: list) -> pd.DataFrame:
    """Turn a /predict request payload into the one-hot row the model expects."""
    row = {col: 0 for col in feature_columns}
    row["Bedroom"] = payload["bedroom"]
    row["Bathroom"] = payload["bathroom"]
    row["Property Size"] = payload["size"]
    row["# of Floors"] = payload["floors"]
    row["Total Units"] = payload["total_units"]
    row["Parking Lot"] = payload["parking"]
    row["Completion Year"] = payload["completion_year"]

    for f in payload.get("facilities", []):
        key = f"Facility_{f}"
        if key in row:
            row[key] = 1
    for n in payload.get("nearby", []):
        key = f"Has_{n}"
        if key in row:
            row[key] = 1
    for key in [
        f"Tenure Type_{payload['tenure']}",
        f"Property Type_{payload['property_type']}",
        f"Floor Range_{payload['floor_range']}",
        f"Land Title_{payload['land_title']}",
        f"State_{payload['state']}",
    ]:
        if key in row:
            row[key] = True

    # City was one-hot encoded at training time too (ds_assignment.py notes
    # it gave the single biggest lift of anything tried), but unlike
    # State/Tenure/etc. it isn't in constants.py - its categories are
    # whatever ended up in feature_columns.pkl. If the caller didn't supply
    # one, or supplied one that isn't among the trained categories, every
    # City_<x> column is simply left at 0 - the same implicit "reference
    # category" behaviour pandas.get_dummies(..., drop_first=True) already
    # gives the single city that has no column at all.
    city = payload.get("city")
    if city:
        city_key = f"City_{city}"
        if city_key in row:
            row[city_key] = True

    return pd.DataFrame([row])[feature_columns]


def predict(payload: dict) -> dict:
    art = load_artifacts()

    X_input = build_feature_row(payload, art.feature_columns)
    X_scaled = art.scaler.transform(X_input)
    prediction = float(art.model.predict(X_scaled)[0])

    size = payload["size"]
    result = {
        "prediction": prediction,
        "price_per_sqft": prediction / size if size else None,
        "best_rmse": None,
        "range_low": None,
        "range_high": None,
        "bracket": None,
        "similar_avg": None,
        "similar_count": 0,
        "diff_pct": None,
        "feature_importances": None,
    }

    if art.results_df is not None:
        try:
            best_rmse = float(art.results_df.sort_values("RMSE").iloc[0]["RMSE"])
            result["best_rmse"] = best_rmse
            result["range_low"] = max(prediction - best_rmse, 0)
            result["range_high"] = prediction + best_rmse
        except Exception:
            pass

    if art.extra is not None:
        edges = art.extra["price_bin_edges"]
        labels = art.extra["price_bin_labels"]
        bracket = pd.cut([prediction], bins=edges, labels=labels)[0]
        result["bracket"] = str(bracket) if bracket is not None and not pd.isna(bracket) else None

    similar = art.sample_df[
        (art.sample_df["State"] == payload["state"])
        & (art.sample_df["Property Type"] == payload["property_type"])
    ]
    if len(similar) >= 3:
        sim_avg = float(similar["price"].mean())
        result["similar_avg"] = sim_avg
        result["similar_count"] = int(len(similar))
        result["diff_pct"] = (prediction - sim_avg) / sim_avg * 100

    if hasattr(art.model, "feature_importances_"):
        importances = pd.Series(art.model.feature_importances_, index=art.feature_columns)
        top = importances.sort_values(ascending=False).head(8)
        result["feature_importances"] = [
            {"feature": k, "importance": float(v)} for k, v in top.items()
        ]

    return result